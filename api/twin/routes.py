@router.put("/scenarios/{sid}", response_model=Scenario)
def update_scenario(sid: str, sc: ScenarioIn, note: Optional[str] = Query(None, max_length=120), ws: str = WS_HEADER):
    owner = _owner(ws)
    body = _body(sc)
    with _db() as con:
        _checked(con, body)
    with state.connect() as s:
        out = state.update(s, owner, sid, body, note or "updated")
        if not out:
            raise HTTPException(404, f"Unknown scenario {sid}")
        return out


